import type { CategoryKey, CheckDefinition, Severity } from "./types";

function d(
  key: string,
  category: CategoryKey,
  label: string,
  severity: Severity,
  weight: number,
  why: string,
  fix: string,
): CheckDefinition {
  return { key, category, label, severity, weight, why, fix };
}

