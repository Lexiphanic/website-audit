export const CHECK_BY_KEY = new Map(CHECK_DEFINITIONS.map((check) => [check.key, check]));

export function definitionFor(key: string): CheckDefinition {
  return (
    CHECK_BY_KEY.get(key) ?? {
      key,
      category: "migration",
      label: key,
      severity: "info",
      weight: 0,
      why: "",
      fix: "",
    }
  );
}

export function checksForCategory(category: CategoryKey): CheckDefinition[] {
  return CHECK_DEFINITIONS.filter((check) => check.category === category);
}
